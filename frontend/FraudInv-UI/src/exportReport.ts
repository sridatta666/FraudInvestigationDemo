export function exportReport(txn: any, events: any[], fraudScore: number | null): void {
  const timestamp = new Date().toLocaleString();
  const riskLabel =
    fraudScore === null ? 'UNKNOWN'
    : fraudScore > 70 ? 'HIGH RISK'
    : fraudScore > 35 ? 'MEDIUM RISK'
    : 'LOW RISK';

  let md = `# AuraGuard Fraud Investigation Report\n\n`;
  md += `**Generated:** ${timestamp}  \n`;
  md += `**Transaction:** ${txn.id}  \n`;
  md += `**Risk Level:** ${riskLabel}${fraudScore !== null ? ` (Score: ${fraudScore}/100)` : ''}\n\n`;
  md += `---\n\n`;
  md += `## Transaction Details\n\n`;
  md += `| Field | Value |\n|---|---|\n`;
  for (const [key, val] of Object.entries(txn)) {
    md += `| ${key} | ${val} |\n`;
  }
  md += `\n`;

  for (const event of events) {
    if (event.output) {
      md += `## ${event.agent} Agent Output\n\n${event.output}\n\n---\n\n`;
    }
  }

  md += `*Report generated by AuraGuard AI Fraud Investigation System*\n`;

  const blob = new Blob([md], { type: 'text/markdown;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `fraud-report-${txn.id}-${Date.now()}.md`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
